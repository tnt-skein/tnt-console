--- Слова рока `argparse` по-русски: отказы разбора и строка вызова.
---
--- Рок говорит по-английски, и слова у него зашиты в код: «missing
--- argument», «unknown option», «Usage:». Разбор при этом его, а не наш,
--- поэтому переводится не разбор, а готовый текст — по образцам целых
--- предложений. Выпуск рока закреплён в рокспеке, и каждое предложение
--- сверено проверкой: новое предложение нового выпуска покажет её отказ,
--- а не английский текст в руках оператора. Незнакомое предложение
--- отдаётся как есть — непереведённый отказ лучше потерянного.
---
--- Подписи групп справки («Аргументы», «Ключи», «Команды») задаются
--- группами при сборке разбора, а слова о значении по умолчанию — своим
--- описанием: переводить здесь приходится только то, что рок не даёт
--- задать.

local Module = {}

--- Начало строки вызова у рока.
local ROCK_USAGE = '^Usage: '

--- Начало строки вызова у нас.
---
--- Ширина та же, семь знаков: продолжение длинной строки вызова рок
--- сдвигает на ширину своего начала, и столбцы остаются ровными.
Module.USAGE = 'Вызов: '

--- Предложения рока и их перевод.
---
--- Образец — предложение целиком, от начала до конца: часть предложения
--- совпала бы и с чужим, более длинным. Имя в кавычках рок берёт у того,
--- кто вызвал, и в нём бывает что угодно, поэтому захват жадный: имя
--- с апострофом внутри остаётся целым.
---@type [string, string][]
local SENTENCES = {
    { "^missing argument '(.*)'$", 'не хватает аргумента «%s»' },
    { "^missing option '(.*)'$", 'не хватает ключа «%s»' },
    { '^too many arguments$', 'лишний аргумент' },
    { "^unknown command '(.*)'$", 'команды «%s» нет' },
    { "^unknown option '(.*)'$", 'ключа «%s» нет' },
    { "^option '(.*)' requires an argument$", 'ключу «%s» нужно значение' },
    { "^option '(.*)' does not take arguments$", 'ключ «%s» значения не берёт' },
    { "^argument for option '(.-)' must be one of '(.*)'$", 'ключ «%s» — одно из «%s»' },
    { "^argument '(.-)' must be one of '(.*)'$", 'аргумент «%s» — одно из «%s»' },
}

--- Подсказки рока: вторая строка отказа о незнакомом имени.
---@type [string, string][]
local TIPS = {
    { "^Did you mean one of these: '(.*)'%?$", 'может быть, одно из: «%s»?' },
    { "^Did you mean '(.*)'%?$", 'может быть, «%s»?' },
}

--- Переводит строку по списку образцов; незнакомую отдаёт как есть.
---
--- Список имён рок пишет в кавычках через запятую («'a', 'b'») либо
--- через пробел («'a' 'b'»); внутренние кавычки становятся нашими.
---@param text string
---@param patterns [string, string][]
---@return string
local function translate(text, patterns)
    for _, pattern in ipairs(patterns) do
        local found = { text:match(pattern[1]) }

        if #found > 0 then
            local last = found[#found]:gsub("',? '", '», «')

            found[#found] = last

            return pattern[2]:format(unpack(found))
        end
    end

    return text
end

--- Отказ разбора по-русски.
---
--- Отказ бывает в две строки: предложение и подсказка с похожими
--- именами. Переводится каждая своими образцами.
---@param message string Отказ, как его отдал рок
---@return string
function Module.refusal(message)
    local sentence, tip = message:match('^([^\n]*)\n(.*)$')

    if sentence == nil then
        return translate(message, SENTENCES)
    end

    return translate(sentence, SENTENCES) .. '\n' .. translate(tip --[[@as string]], TIPS)
end

--- Текст рока с нашей строкой вызова: справка либо сама строка вызова.
---
--- Образец привязан к началу текста, и замена бывает не больше одной:
--- слово «Usage:» в описании команды остаётся словом.
---@param text string `get_help()` либо `get_usage()` разбора
---@return string
function Module.usage(text)
    return (text:gsub(ROCK_USAGE, Module.USAGE))
end

return Module
